export type GlyphName = keyof typeof GLYPHS;

/** An SVG path of `#` runs, one row per line (also draws a glyph mid-boil, see resolve.ts) */
export const pathFor = (rows: readonly string[]): string => {
  let d = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; ) {
      if (row[x] !== '#') {
        x++;
        continue;
      }
      let end = x;
      while (row[end] === '#') end++;
      d += `M${x} ${y}h${end - x}v1h-${end - x}z`;
      x = end;
    }
  });
  return d;
};

export const GLYPH_PATHS = Object.fromEntries(Object.entries(GLYPHS).map(([name, rows]) => [name, pathFor(rows)])) as Record<GlyphName, string>;
